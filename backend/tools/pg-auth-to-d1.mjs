/**
 * Copies Better Auth's own rows out of Postgres and into D1.
 *
 * Better Auth was the last thing still reading Postgres: IdentityService wrote
 * the identity rows to D1 while Better Auth itself read them from Supabase, so
 * the two halves of an account lived in different databases and every sign-in
 * left Cloudflare. Moving the adapter without moving these rows would lock
 * everybody out, because the password hashes live here.
 *
 * Reads only. Postgres is left exactly as it is, so it stays available as the
 * fallback until the switch is confirmed working.
 *
 * Writes INSERT OR IGNORE keyed on the id, so a re-run adds what is missing and
 * changes nothing that is already there.
 *
 *   node tools/pg-auth-to-d1.mjs > /tmp/auth.sql
 *   npx wrangler d1 execute clams-d1 --remote --file /tmp/auth.sql
 */
import { readFileSync } from 'node:fs';
import pg from 'pg';

const url = (() => {
  const fromEnv = process.env.DATABASE_URL;
  if (fromEnv) return fromEnv;
  const line = readFileSync('.dev.vars', 'utf8').match(/^DATABASE_URL=(.*)$/m);
  if (!line) throw new Error('No DATABASE_URL in the environment or .dev.vars');
  return line[1].trim().replace(/^["']|["']$/g, '');
})();

/**
 * SQL literal.
 *
 * The timestamp columns are integers of milliseconds on D1, and pg hands
 * numerics back as strings — quoting those would store '1783940057077.000000'
 * as text in an integer column, where every Date built from it comes out
 * invalid. So the columns that hold a time are named, and written as whole
 * numbers.
 */
const TIME_COLUMNS = new Set([
  'created_at',
  'updated_at',
  'expires_at',
  'access_token_expires_at',
  'refresh_token_expires_at',
]);

const lit = (v, col) => {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'boolean') return v ? '1' : '0';
  if (TIME_COLUMNS.has(col)) return String(Math.round(Number(v)));
  if (typeof v === 'number') return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
};

const rows = (table, cols, records) =>
  records
    .map(
      (r) =>
        `INSERT OR IGNORE INTO ${table} (${cols.join(', ')}) VALUES (${cols
          .map((c) => lit(r[c], c))
          .join(', ')});`,
    )
    .join('\n');

const client = new pg.Client({ connectionString: url });
await client.connect();

const ms = (col) => `extract(epoch from ${col}) * 1000 as ${col}`;

const users = await client.query(`
  SELECT id::text, name, email, email_verified, image, username, display_username,
         ${ms('created_at')}, ${ms('updated_at')}
    FROM auth_user`);

const accounts = await client.query(`
  SELECT id::text, account_id, provider_id, user_id::text, password,
         access_token, refresh_token, id_token, scope,
         ${ms('access_token_expires_at')}, ${ms('refresh_token_expires_at')},
         ${ms('created_at')}, ${ms('updated_at')}
    FROM auth_account`);

// Only sessions that are still good. Copying the expired ones would carry a
// year of dead rows across for nothing.
const sessions = await client.query(`
  SELECT id::text, token, ${ms('expires_at')}, ip_address, user_agent, user_id::text,
         ${ms('created_at')}, ${ms('updated_at')}
    FROM auth_session WHERE expires_at > now()`);

const verifications = await client.query(`
  SELECT id::text, identifier, value, ${ms('expires_at')},
         ${ms('created_at')}, ${ms('updated_at')}
    FROM auth_verification WHERE expires_at > now()`);

await client.end();

console.log('-- Generated by tools/pg-auth-to-d1.mjs. Postgres was read, never written.');
console.log(
  rows(
    'auth_user',
    ['id', 'name', 'email', 'email_verified', 'image', 'username', 'display_username', 'created_at', 'updated_at'],
    users.rows,
  ),
);
console.log(
  rows(
    'auth_account',
    [
      'id', 'account_id', 'provider_id', 'user_id', 'password', 'access_token', 'refresh_token',
      'id_token', 'scope', 'access_token_expires_at', 'refresh_token_expires_at',
      'created_at', 'updated_at',
    ],
    accounts.rows,
  ),
);
console.log(
  rows(
    'auth_session',
    ['id', 'token', 'expires_at', 'ip_address', 'user_agent', 'user_id', 'created_at', 'updated_at'],
    sessions.rows,
  ),
);
console.log(
  rows(
    'auth_verification',
    ['id', 'identifier', 'value', 'expires_at', 'created_at', 'updated_at'],
    verifications.rows,
  ),
);

console.error(
  `users ${users.rowCount}, accounts ${accounts.rowCount} ` +
    `(${accounts.rows.filter((a) => a.password).length} with a password), ` +
    `live sessions ${sessions.rowCount}, live verifications ${verifications.rowCount}`,
);
