/**
 * Generates a Drizzle SQLite schema from schema.prisma.
 *
 * Written rather than hand-converted because there are thirty-one models and
 * several hundred columns, and a hand port of that is a transcription exercise
 * with a silent failure mode: one column typed as text instead of an integer
 * and the data lands looking fine until something compares it.
 *
 * The type mapping is the whole point, so it is stated explicitly:
 *
 *   @db.Uuid          -> text          ids keep their exact values, so every
 *                                      foreign key still lines up afterwards
 *   @db.Timestamptz   -> integer ms    SQLite has no timestamp; text sorts
 *                                      '2026-9-8' before '2026-10-1'
 *   @db.Date          -> text          a calendar day, not an instant — giving
 *                                      it a time component is how a day drifts
 *   @db.Time          -> text 'HH:MM'  only ever compared and displayed
 *   Boolean           -> integer bool
 *   Json              -> text          stored as JSON, read back whole
 *   Bytes             -> blob          ciphertext; must survive byte for byte
 *   BigInt            -> integer
 *   enum              -> text          SQLite has no enum type
 *
 * Relations are emitted as plain columns without foreign keys. D1 enforces
 * them, and a bulk load in an order that satisfies every constraint is a
 * problem to solve when the data is known to be good, not during the copy.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync('prisma/schema.prisma', 'utf8');

const enums = new Set([...src.matchAll(/^enum\s+(\w+)\s*\{/gm)].map((m) => m[1]));
const models = [...src.matchAll(/^model\s+(\w+)\s*\{([\s\S]*?)^\}/gm)];

const camel = (s) => s.replace(/_([a-z])/g, (_, c) => c.toUpperCase());

function columnFor(line, modelNames) {
  const m = line.match(/^\s*(\w+)\s+(\w+)(\[\])?(\?)?\s*(.*)$/);
  if (!m) return null;
  const [, name, type, isList, optional, rest] = m;
  if (isList) return null;                    // a relation array, not a column
  if (modelNames.has(type)) return null;      // a relation object
  if (rest.includes('@relation')) return null;

  const dbName = (rest.match(/@map\("([^"]+)"\)/) || [])[1] ?? name;
  const isId = /@id\b/.test(rest);
  const isUnique = /@unique\b/.test(rest);
  const notNull = !optional;

  let col;
  if (type === 'String') col = `text('${dbName}')`;
  else if (type === 'Int') col = `integer('${dbName}')`;
  else if (type === 'BigInt') col = `integer('${dbName}')`;
  else if (type === 'Float' || type === 'Decimal') col = `real('${dbName}')`;
  else if (type === 'Boolean') col = `integer('${dbName}', { mode: 'boolean' })`;
  else if (type === 'Json') col = `text('${dbName}')`;
  // 'buffer' mode, so ciphertext and image bytes come back as a Buffer rather
  // than as `unknown` that every reader has to cast.
  else if (type === 'Bytes') col = `blob('${dbName}', { mode: 'buffer' })`;
  else if (enums.has(type)) col = `text('${dbName}')`;
  else if (type === 'DateTime') {
    if (/@db\.Date\b/.test(rest)) col = `text('${dbName}')`;
    else if (/@db\.Time\b/.test(rest)) col = `text('${dbName}')`;
    else col = `integer('${dbName}', { mode: 'timestamp_ms' })`;
  } else return null;

  if (isId) col += '.primaryKey()';
  else if (notNull) col += '.notNull()';
  if (isUnique && !isId) col += '.unique()';

  // Defaults are deliberately not carried over. Every row being loaded already
  // has a value for every column, and a default that disagreed with Postgres's
  // would only apply to rows written later — a difference nothing would notice
  // until it mattered.
  return `  ${camel(name)}: ${col},`;
}

const out = [
  "import { blob, integer, real, sqliteTable, text } from 'drizzle-orm/sqlite-core';",
  '',
  '/**',
  ' * GENERATED by tools/prisma-to-drizzle.mjs from schema.prisma. Do not edit by',
  ' * hand — regenerate, or the two drift and the migration writes into columns',
  ' * that no longer mean what the code thinks they mean.',
  ' *',
  ' * See the generator for the type mapping and why each choice was made.',
  ' */',
  '',
];

const modelNames = new Set(models.map((m) => m[1]));
let tableCount = 0;
let columnCount = 0;

for (const [, modelName, body] of models) {
  const table = (body.match(/@@map\("([^"]+)"\)/) || [])[1] ?? modelName.toLowerCase();
  const cols = body
    .split('\n')
    .filter((l) => !l.trim().startsWith('//') && !l.trim().startsWith('@@') && l.trim())
    .map((l) => columnFor(l, modelNames))
    .filter(Boolean);
  if (!cols.length) continue;
  tableCount++;
  columnCount += cols.length;
  out.push(`export const ${camel(table)} = sqliteTable('${table}', {`, ...cols, '});', '');
}

writeFileSync('src/infra/d1/schema.generated.ts', out.join('\n'));
console.log(`generated ${tableCount} tables, ${columnCount} columns`);
